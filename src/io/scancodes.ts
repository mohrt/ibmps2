/** Pause has no break code; this is its whole make sequence. */
export const SET2_PAUSE = [0xe1, 0x14, 0x77, 0xe1, 0xf0, 0x14, 0xf0, 0x77];

export function set2Break(make: number[]): number[] {
  if (make.length === 4) return [0xe0, 0xf0, 0x7c, 0xe0, 0xf0, 0x12];
  return make.length === 2 ? [0xe0, 0xf0, make[1]] : [0xf0, make[0]];
}

